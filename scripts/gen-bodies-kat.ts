/**
 * Writes test/fixtures/bodies_kat.json: known answers for `src/bodies/`, made
 * from fixed keys and fixed times. @bsv/sdk signs with an RFC 6979 nonce, so
 * every run writes the same bytes; test/bodies_kat.test.ts regenerates the
 * file and compares it byte for byte.
 *
 *   bun scripts/gen-bodies-kat.ts
 *
 * Each key is the SHA-256 of `gip-v2-bodies-kat/<label>`, read as a scalar.
 *
 * It pins a rotation: node-1 signed the vouch, node-2 now signs the list, and
 * the list carries both delegations, node-2's first. A port that looks only
 * at the first delegation, or only at the list signer's, gets it wrong.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PrivateKey } from '@bsv/sdk';
import {
  BODY_VOUCH_PURPOSE,
  type BodyClaim,
  delegateSigner,
  didKeyOfSecret,
  issueRegistryEntry,
  issueStatusList,
  issueVouch,
  present,
  appPlace,
  placeInvoice,
  placeKeyOf,
  readRegistryEntry,
  verifyPresentation,
} from '../src';

export const KAT_PATH = join(import.meta.dir, '../test/fixtures/bodies_kat.json');

const LABEL = 'gip-v2-bodies-kat';
/** The generator's key for a label, so a test can sign beside it. */
export const katKey = (label: string): PrivateKey =>
  PrivateKey.fromString(createHash('sha256').update(`${LABEL}/${label}`).digest('hex'), 16);
const key = katKey;
const pub = (k: PrivateKey): string => k.toPublicKey().toString();

export function buildBodiesKat(): string {
  const steward = key('steward');
  const anchor = key('hillside/anchor');
  const node = key('hillside/node-1');
  const listNode = key('hillside/node-2');
  const holderRoot = key('holder/root');

  const now = Date.UTC(2026, 10, 4, 12) / 1000; // 2026-11-04T12:00:00Z
  const relyingParty = 'kids-world:gem-island';
  const nonce = 'kat-nonce-0001';
  const did = 'did:web:hillside.example.edu.au';
  const url = 'https://hillside.example.edu.au/status/1';
  const require: BodyClaim = 'member';

  // The holder's key at the kids' world: its place key (decision 11), for the place app:kids-world:gem-island.
  const place = appPlace(relyingParty);
  const subjectSk = placeKeyOf(holderRoot, place);
  const registryEntry = issueRegistryEntry(steward, {
    did,
    anchor: pub(anchor),
    kind: 'school',
    claims: ['member', 'guardian_of_member'],
    periodEnds: ['2026-12-31T23:59:59Z', '2027-12-31T23:59:59Z'],
    statusList: url,
    validFrom: '2026-01-01T00:00:00Z',
    validUntil: '2027-12-31T23:59:59Z',
  });
  const entry = readRegistryEntry(registryEntry);
  if (entry === null) throw new Error('registry entry did not read back');
  const delegations = [
    delegateSigner(anchor, pub(listNode), BODY_VOUCH_PURPOSE),
    delegateSigner(anchor, pub(node), BODY_VOUCH_PURPOSE),
  ];
  const vouch = issueVouch({
    nodeSk: node,
    entry,
    subject: didKeyOfSecret(subjectSk),
    claim: 'member',
    statusIndex: 42,
    validFrom: '2026-11-04T09:00:00Z',
    validUntil: '2026-12-31T23:59:59Z',
  });
  // Index 41 is withdrawn, so a reader that is off by one bit gets it wrong.
  const statusList = issueStatusList(listNode, { issuer: did, delegations, url, revoked: [41], validFrom: '2026-11-04T00:00:00Z' });
  const presentation = present({ credentialJwt: vouch, subjectSk, audience: relyingParty, nonce, at: now });

  const stewards = [didKeyOfSecret(steward)];
  const result = verifyPresentation(presentation, {
    audience: relyingParty,
    nonce,
    stewards: new Set(stewards),
    registryEntries: [registryEntry],
    statusLists: { [url]: statusList },
    now,
    require,
  });

  const out = {
    about:
      'Known answers for plexus-gip src/bodies. Generated by scripts/gen-bodies-kat.ts; each key is sha256("gip-v2-bodies-kat/<label>"). The vouch carries no delegation: node-1 signed it, node-2 signs the list, and the list carries both delegations as evidence, node-2\'s first. The holder\'s key is its place key for app:kids-world:gem-island (src/places, placeKeyOf). The expected result is also written by hand in test/bodies_kat.test.ts.',
    parties: {
      steward: didKeyOfSecret(steward),
      anchor: pub(anchor),
      node: didKeyOfSecret(node),
      listNode: didKeyOfSecret(listNode),
      holderRoot: pub(holderRoot),
      subject: didKeyOfSecret(subjectSk),
    },
    place: {
      relyingParty,
      place,
      invoice: placeInvoice(place),
      subject: didKeyOfSecret(subjectSk),
    },
    registryEntry,
    vouch,
    statusList: { url, revoked: [41], delegations, jwt: statusList },
    presentation,
    verify: {
      options: { audience: relyingParty, nonce, stewards, now, require },
      result,
    },
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(KAT_PATH, buildBodiesKat());
  console.log(`wrote ${KAT_PATH}`);
}
