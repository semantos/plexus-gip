/**
 * Writes test/fixtures/collect_kat.json: known answers for the holder's proofs
 * at an office's `POST /collect`, the plain collect and the extension to a new
 * place (semantos-core CLAIMS-AND-REQUIREMENTS.md, decision 12; see
 * `bodies/office/office.ts`, `extendNonce`). test/collect_kat.test.ts
 * regenerates the file and compares it byte for byte.
 *
 *   bun scripts/gen-collect-kat.ts
 *
 * The roots are those of test/fixtures/bodies_kat.json (`katKey`), so the held
 * key here is that file's subject: its key for app:kids-world:gem-island. The
 * new place is a web site, chosen after the desk.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { didKeyOfSecret, fromB64url, fromUtf8 } from '../src/bodies';
import { appPlace, originOf, placeKeyOf } from '../src/places';
import {
  COLLECT_NONCE,
  PICKUP_PROOF_TYP,
  collectProof,
  extendNonce,
  extendProof,
  guardianNonce,
  guardianProof,
} from '../bodies/office/office';
import { katKey } from './gen-bodies-kat';

export const COLLECT_KAT_PATH = join(import.meta.dir, '../test/fixtures/collect_kat.json');

const part = (jwt: string, i: number) => JSON.parse(fromUtf8(fromB64url(jwt.split('.')[i]!)));
const shown = (jwt: string) => ({ header: part(jwt, 0), payload: part(jwt, 1), jwt });

export function buildCollectKat(): string {
  const body = 'did:web:hillside.example.edu.au';
  const at = Date.UTC(2026, 10, 7, 9) / 1000; // 2026-11-07T09:00:00Z
  const heldPlace = appPlace('kids-world:gem-island');
  const newPlace = originOf('https://lessons.example/');
  const childRoot = katKey('holder/root');
  const guardianRoot = katKey('guardian/root');

  const heldSk = placeKeyOf(childRoot, heldPlace);
  const newSk = placeKeyOf(childRoot, newPlace);
  const guardianSk = placeKeyOf(guardianRoot, heldPlace);
  const newSubject = didKeyOfSecret(newSk);

  const proof = collectProof({ subjectSk: newSk, body, at });
  const extend = extendProof({ heldSk, body, newSubject, at });
  const guardian = guardianProof({ guardianSk, body, newSubject, at });

  const out = {
    about:
      'Known answers for the holder\'s proofs at an office\'s POST /collect, plain and extending to a new place (decision 12). Generated by scripts/gen-collect-kat.ts. The roots are test/fixtures/bodies_kat.json\'s (sha256("gip-v2-bodies-kat/<label>")); each key is placeKeyOf(root, place). Each proof is an ' +
      `${PICKUP_PROOF_TYP} JWT {aud, nonce, iat}, accepted within 300 s of the office's clock. A request for an adult member's row leaves out guardian.`,
    body,
    at,
    keys: {
      held: { root: 'holder/root', place: heldPlace, did: didKeyOfSecret(heldSk) },
      new: { root: 'holder/root', place: newPlace, did: newSubject },
      guardian: { root: 'guardian/root', place: heldPlace, did: didKeyOfSecret(guardianSk) },
    },
    nonces: { collect: COLLECT_NONCE, extend: extendNonce(newSubject), guardian: guardianNonce(newSubject) },
    proofs: { collect: shown(proof), extend: shown(extend), guardian: shown(guardian) },
    request: { method: 'POST', path: '/collect', body: { proof, extend, guardian } },
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(COLLECT_KAT_PATH, buildCollectKat());
  console.log(`wrote ${COLLECT_KAT_PATH}`);
}
