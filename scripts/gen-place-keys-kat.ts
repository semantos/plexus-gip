/**
 * Writes test/fixtures/place_keys_kat.json: known answers for a person's key at a place, under both derivations in
 * use today (`relationshipKey` in src/bodies, `siteKeyOf` in src/places). test/place_keys_kat.test.ts regenerates the
 * file and compares it byte for byte.
 *
 *   bun scripts/gen-place-keys-kat.ts
 *
 * Each root is the SHA-256 of `gip-v2-place-keys-kat/<label>`, read as a scalar, except `bodies-kat-holder`, which is
 * the holder root of test/fixtures/bodies_kat.json, so the two files are tied together.
 *
 * Web places get both keys; an app's id (`kids-world:gem-island`) gets only the relationship key, since `siteKeyOf`
 * takes web origins. The file pins what the code does now, and changes only when decision 11 does.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PrivateKey } from '@bsv/sdk';
import { didKeyOf, relationshipKey, WireError } from '../src/bodies';
import { originOf, SITE_KEY_VERSION, siteKeyInvoice, siteKeyOf } from '../src/places';
import { katKey as bodiesKatKey } from './gen-bodies-kat';

export const PLACE_KEYS_KAT_PATH = join(import.meta.dir, '../test/fixtures/place_keys_kat.json');

const LABEL = 'gip-v2-place-keys-kat';
export const placeKatKey = (label: string): PrivateKey =>
  PrivateKey.fromString(createHash('sha256').update(`${LABEL}/${label}`).digest('hex'), 16);

/** Addresses and the origin each serialises to, or the refusal. */
export const ORIGIN_CASES: readonly string[] = [
  'https://Lessons.Example:443/packs?x#y',
  'http://localhost:5173/',
  'https://BÜCHER.example/x',
  'https://hillside.example.edu.au:8443/a',
  'https://[::1]:8443/',
  'not a url',
  'ws://x.example/',
  'blob:https://a.example/uuid',
  'data:text/plain,hi',
  'file:///etc/passwd',
];

const WEB_PLACES = ['https://lessons.example', 'http://localhost:5173', 'https://xn--bcher-kva.example'];
const APP_PLACES = ['kids-world:gem-island', 'vedic-math-lab:app'];

const relationshipInvoice = (place: string): string =>
  `relationship-${createHash('sha256').update(place, 'utf8').digest('hex').slice(0, 16)}:1:0`;

const keyEntry = (invoice: string, sk: PrivateKey) => ({
  invoice,
  publicKey: sk.toPublicKey().toString(),
  didKey: didKeyOf(sk.toPublicKey()),
});

export function buildPlaceKeysKat(): string {
  const roots: Array<[string, PrivateKey]> = [
    ['guardian', placeKatKey('guardian')],
    ['child-seat', placeKatKey('child-seat')],
    ['bodies-kat-holder', bodiesKatKey('holder/root')],
  ];

  const origins = ORIGIN_CASES.map((address) => {
    try {
      return { address, origin: originOf(address) };
    } catch (e) {
      if (!(e instanceof WireError)) throw e;
      return { address, refused: e.code };
    }
  });

  const kat = {
    about:
      "Known answers for a person's key at a place, under both derivations in use today. Generated by " +
      'scripts/gen-place-keys-kat.ts; canonical here, copied byte for byte by every other implementation. ' +
      "relationshipKey is BRC-42 to self under 'relationship-<first 16 hex of sha256(place)>:1:0' (src/bodies; a " +
      "body's vouch names it). siteKey is BRC-42 to self under '2-admin plexus site-<origin> <version>' (src/places; " +
      "the Plexus Auth approver signs in with it). For one web site they differ: which becomes the one place key is " +
      "decision 11 of semantos-core docs/design/CLAIMS-AND-REQUIREMENTS.md. Roots are sha256('gip-v2-place-keys-kat/" +
      "<label>') read as a scalar; bodies-kat-holder is the holder root of bodies_kat.json.",
    siteKeyVersion: SITE_KEY_VERSION,
    origins,
    roots: roots.map(([label, root]) => ({
      label,
      root: root.toHex().padStart(64, '0'),
      rootPublicKey: root.toPublicKey().toString(),
      places: [
        ...WEB_PLACES.map((place) => ({
          place,
          relationshipKey: keyEntry(relationshipInvoice(place), relationshipKey(root, place)),
          siteKey: keyEntry(siteKeyInvoice(place), siteKeyOf(root, place)),
        })),
        ...APP_PLACES.map((place) => ({
          place,
          relationshipKey: keyEntry(relationshipInvoice(place), relationshipKey(root, place)),
        })),
      ],
    })),
  };
  return `${JSON.stringify(kat, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(PLACE_KEYS_KAT_PATH, buildPlaceKeysKat());
  console.log(`wrote ${PLACE_KEYS_KAT_PATH}`);
}
