/**
 * Writes test/fixtures/place_keys_kat.json: known answers for a person's key at a place, `placeKeyOf` in src/places
 * (semantos-core CLAIMS-AND-REQUIREMENTS.md, decision 11). test/place_keys_kat.test.ts regenerates the file and
 * compares it byte for byte.
 *
 *   bun scripts/gen-place-keys-kat.ts
 *
 * Each root is the SHA-256 of `gip-v2-place-keys-kat/<label>`, read as a scalar, except `bodies-kat-holder`, which is
 * the holder root of test/fixtures/bodies_kat.json, so the two files are tied together.
 *
 * Every root has a key at every place: three web sites (by their origins) and two apps (`app:<id>`). The file also
 * pins how an address becomes an origin, how an app's id becomes a place, and what is refused.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PrivateKey } from '@bsv/sdk';
import { didKeyOf, WireError } from '../src/bodies';
import { appPlace, isPlace, originOf, PLACE_KEY_VERSION, placeInvoice, placeKeyOf } from '../src/places';
import { katKey as bodiesKatKey } from './gen-bodies-kat';

export const PLACE_KEYS_KAT_PATH = join(import.meta.dir, '../test/fixtures/place_keys_kat.json');

const LABEL = 'gip-v2-place-keys-kat';
export const placeKatKey = (label: string): PrivateKey =>
  PrivateKey.fromString(createHash('sha256').update(`${LABEL}/${label}`).digest('hex'), 16);

/** Addresses and the origin each serialises to, or the refusal. */
export const ORIGIN_CASES: readonly string[] = [
  'https://Lessons.Example:443/packs?x#y',
  'http://localhost:5173/',
  'https://BÜCHER.example/x',
  'https://hillside.example.edu.au:8443/a',
  'https://[::1]:8443/',
  'not a url',
  'ws://x.example/',
  'blob:https://a.example/uuid',
  'data:text/plain,hi',
  'file:///etc/passwd',
];

/** Apps' ids, as a seat card writes them, and the place each is, or the refusal. */
export const APP_CASES: readonly string[] = ['kids-world:gem-island', 'vedic-math-lab:app', 'Kids-World:gem-island', 'kidsworld', 'a:b:c', 'a:', ''];

/** Strings that are not places as written, and must be refused. */
export const NOT_PLACES: readonly string[] = [
  'kids-world:gem-island', // an app's id is not its place
  'https://Lessons.example',
  'https://lessons.example/',
  'https://lessons.example:443',
  'app:Kids:x',
  'app:',
  'ws://x.example',
  'lessons.example',
  '',
];

const PLACES = [
  'https://lessons.example',
  'http://localhost:5173',
  'https://xn--bcher-kva.example',
  'app:kids-world:gem-island',
  'app:vedic-math-lab:app',
];

const refusalOf = (f: () => unknown) => {
  try {
    f();
    return null;
  } catch (e) {
    if (!(e instanceof WireError)) throw e;
    return e.code;
  }
};

export function buildPlaceKeysKat(): string {
  const roots: Array<[string, PrivateKey]> = [
    ['guardian', placeKatKey('guardian')],
    ['child-seat', placeKatKey('child-seat')],
    ['bodies-kat-holder', bodiesKatKey('holder/root')],
  ];
  const origins = ORIGIN_CASES.map((address) => {
    const refused = refusalOf(() => originOf(address));
    return refused === null ? { address, origin: originOf(address) } : { address, refused };
  });
  const apps = APP_CASES.map((id) => {
    const refused = refusalOf(() => appPlace(id));
    return refused === null ? { id, place: appPlace(id) } : { id, refused };
  });
  for (const p of NOT_PLACES) if (isPlace(p)) throw new Error(`taken as a place: ${p}`);

  const kat = {
    about:
      "Known answers for a person's key at a place: placeKeyOf(root, place), BRC-42 to the root itself under " +
      "'2-admin plexus site-<place> <version>' (src/places; semantos-core CLAIMS-AND-REQUIREMENTS.md decision 11). " +
      'A place is a WHATWG http(s) origin or app:<id>; for an origin it is the key the Plexus Auth approver signs in ' +
      'with. Generated by scripts/gen-place-keys-kat.ts; canonical here, copied byte for byte by every other ' +
      "implementation. Roots are sha256('gip-v2-place-keys-kat/<label>') read as a scalar; bodies-kat-holder is the " +
      'holder root of bodies_kat.json.',
    placeKeyVersion: PLACE_KEY_VERSION,
    origins,
    apps,
    notPlaces: NOT_PLACES.map((place) => ({ place, refused: refusalOf(() => placeInvoice(place)) })),
    roots: roots.map(([label, root]) => ({
      label,
      root: root.toHex().padStart(64, '0'),
      rootPublicKey: root.toPublicKey().toString(),
      places: PLACES.map((place) => {
        const sk = placeKeyOf(root, place);
        return { place, invoice: placeInvoice(place), publicKey: sk.toPublicKey().toString(), didKey: didKeyOf(sk.toPublicKey()) };
      }),
    })),
  };
  return `${JSON.stringify(kat, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(PLACE_KEYS_KAT_PATH, buildPlaceKeysKat());
  console.log(`wrote ${PLACE_KEYS_KAT_PATH}`);
}
